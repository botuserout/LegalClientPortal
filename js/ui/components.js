export function renderStatusBadge(status) {
  const s = (status || '').toLowerCase();
  let badgeClass = 'badge-neutral';
  
  if (s.includes('completed') || s.includes('verified') || s.includes('accepted') || s.includes('synced') || s.includes('paid')) {
    badgeClass = 'badge-success';
  } else if (s.includes('progress') || s.includes('current') || s.includes('quote sent') || s.includes('under review')) {
    badgeClass = 'badge-info';
  } else if (s.includes('action') || s.includes('under process') || s.includes('requested')) {
    badgeClass = 'badge-warning';
  } else if (s.includes('rejected') || s.includes('failed') || s.includes('declined')) {
    badgeClass = 'badge-danger';
  }

  return `
    <span class="badge ${badgeClass}">
      <span class="badge-dot"></span>
      ${status}
    </span>
  `;
}

export function renderProgressBar(percentage) {
  const isComplete = percentage >= 100;
  return `
    <div class="progress-wrapper">
      <div class="progress-header">
        <span>Progress</span>
        <span>${percentage}%</span>
      </div>
      <div class="progress-track">
        <div class="progress-fill ${isComplete ? 'complete' : ''}" style="width: ${Math.min(100, Math.max(0, percentage))}%;"></div>
      </div>
    </div>
  `;
}

export function renderTimeline(stages, currentStageIndex = 0) {
  if (!stages || !stages.length) return '';

  return `
    <div class="timeline-container">
      ${stages.map((st, idx) => {
        let stateClass = 'pending';
        let nodeIcon = (idx + 1).toString();

        if (st.status === 'COMPLETED' || idx < currentStageIndex) {
          stateClass = 'completed';
          nodeIcon = icons.check;
        } else if (st.status === 'CURRENT' || idx === currentStageIndex) {
          stateClass = 'current';
          nodeIcon = '●';
        }

        return `
          <div class="timeline-step ${stateClass}">
            <div class="step-node">${nodeIcon}</div>
            <div class="step-content">
              <div class="step-title">${st.name}</div>
              ${st.completedOn ? `<div class="step-date">${icons.check} Completed on ${st.completedOn}</div>` : ''}
              ${stateClass === 'current' ? `<div class="step-date" style="color: var(--primary-500);">${icons.sync} Currently in progress</div>` : ''}
              ${st.description ? `<div class="step-desc">${st.description}</div>` : ''}
            </div>
          </div>
        `;
      }).join('')}
    </div>
  `;
}

